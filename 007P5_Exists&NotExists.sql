SELECT * 
FROM CUSTOMERS C
WHERE EXISTS (SELECT 1 FROM ORDERS O WHERE O.CUSTOMER_ID = C.CUSTOMER_ID)
AND NOT EXISTS (SELECT 1 FROM ORDERS O WHERE O.CUSTOMER_ID = C.CUSTOMER_ID AND O.STATUS = 'CANCELLED');

SELECT *
FROM PRODUCTS P
WHERE EXISTS (SELECT 1 FROM ORDERS O WHERE O.PRODUCT_ID = P.PRODUCT_ID)
AND NOT EXISTS (SELECT 1 FROM RETURNS R WHERE R.PRODUCT_ID = P.PRODUCT_ID);

SELECT *
FROM EMPLOYEES E
WHERE EXISTS (SELECT 1 FROM EMPLOYEEPROJECTS EP WHERE EP.EMPLOYEE_ID = E.EMPLOYEE_ID)
AND NOT EXISTS (SELECT 1 FROM EMPLOYEEPROJECTS EP WHERE EP.EMPLOYEE_ID = E.EMPLOYEE_ID AND EP.STATUS = 'COMPLETED');

