FROM PRODUCTS P
WHERE EXISTS (SELECT 1 FROM ORDERS O WHERE O.PRODUCT_ID = P.PRODUCT_ID)
AND NOT EXISTS (SELECT 1 FROM ORDERS O WHERE O.PRODUCT_ID = P.PRODUCT_ID AND O.QUANTITY > 20);

