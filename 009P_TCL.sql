/* SQL TRANSACTION CONTROL

A. AUTOCOMMIT

1. CREATE A TABLE NAMED EMPLOYEES WITH EMPLOYEEID, EMPLOYEENAME, DEPARTMENT, AND SALARY. INSERT ONE RECORD AND VERIFY WHETHER THE RECORD
IS AUTOMATICALLY COMMITTED.
2. CHECK THE CURRENT AUTOCOMMIT SETTING IN MYSQL.
3. DISABLE AUTOCOMMIT AND INSERT A NEW EMPLOYEE RECORD. VERIFY THE RECORD BEFORE AND AFTER CLOSING/REOPENING THE TRANSACTION.
4. WITH AUTOCOMMIT DISABLED, INSERT THREE EMPLOYEE RECORDS AND VERIFY THAT ALL THREE RECORDS ARE PART OF THE SAME TRANSACTION.
5. ENABLE AUTOCOMMIT AGAIN AND INSERT A NEW EMPLOYEE RECORD. VERIFY WHETHER THE CHANGE IS COMMITTED AUTOMATICALLY. */ 

CREATE TABLE EMPLOYEES (
EMPLOYEEID INT PRIMARY KEY,
EMPLOYEENAME VARCHAR(100),
DEPARTMENT VARCHAR(100),
SALARY DECIMAL(10,2)
);

INSERT INTO EMPLOYEES
VALUES (1,'JOHN','HR',50000);

SELECT * FROM EMPLOYEES;

SELECT @@AUTOCOMMIT;

SET AUTOCOMMIT = 0;

INSERT INTO EMPLOYEES
VALUES (2,'SMITH','IT',60000);

SELECT * FROM EMPLOYEES;

COMMIT;

SELECT * FROM EMPLOYEES;

SET AUTOCOMMIT = 0;

INSERT INTO EMPLOYEES
VALUES (3,'DAVID','SALES',55000);

INSERT INTO EMPLOYEES
VALUES (4,'MARY','FINANCE',65000);

INSERT INTO EMPLOYEES
VALUES (5,'JAMES','IT',70000);

SELECT * FROM EMPLOYEES;

COMMIT;

SET AUTOCOMMIT = 1;

INSERT INTO EMPLOYEES
VALUES (6,'LINDA','HR',58000);

SELECT * FROM EMPLOYEES;

/* B. COMMIT

6. DISABLE AUTOCOMMIT, INSERT FIVE EMPLOYEE RECORDS, AND USE COMMIT TO PERMANENTLY SAVE THE CHANGES.
7. UPDATE THE SALARY OF AN EMPLOYEE, VERIFY THE UPDATED VALUE, AND USE COMMIT TO PERMANENTLY SAVE THE CHANGE.
8. DELETE ONE EMPLOYEE RECORD, VERIFY THE DELETION, AND USE COMMIT TO PERMANENTLY SAVE THE DELETION.
9. PERFORM AN INSERT, UPDATE, AND DELETE WITHIN THE SAME TRANSACTION AND USE A SINGLE COMMIT TO SAVE ALL THREE CHANGES.
10. INSERT TWO NEW PRODUCTS, UPDATE THE PRICE OF AN EXISTING PRODUCT, AND USE COMMIT TO SAVE ALL CHANGES PERMANENTLY. */

