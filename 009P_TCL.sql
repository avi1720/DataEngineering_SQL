/* C. ROLLBACK

11. DISABLE AUTOCOMMIT, INSERT THREE EMPLOYEE RECORDS, AND USE ROLLBACK. VERIFY WHETHER THE INSERTED RECORDS STILL EXIST.
12. UPDATE THE SALARY OF AN EMPLOYEE AND USE ROLLBACK BEFORE COMMITTING. VERIFY THAT THE ORIGINAL SALARY IS RESTORED.
13. DELETE TWO EMPLOYEE RECORDS AND USE ROLLBACK. VERIFY WHETHER THE DELETED RECORDS ARE RESTORED.
14. PERFORM AN INSERT, UPDATE, AND DELETE IN ONE TRANSACTION. USE ROLLBACK AND VERIFY THE STATE OF THE TABLE.
15. PERFORM THE FOLLOWING TRANSACTION:

• DISABLE AUTOCOMMIT
• INSERT TWO RECORDS
• UPDATE ONE EXISTING RECORD
• DELETE ONE RECORD

• VERIFY ALL CHANGES
• USE ROLLBACK
• VERIFY THE TABLE AGAIN
