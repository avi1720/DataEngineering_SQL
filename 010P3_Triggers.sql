CREATE TRIGGER TRG_PREVENT_SALARY_REDUCTION
ON EMPLOYEES
INSTEAD OF UPDATE
AS
BEGIN
    IF EXISTS
    (
        SELECT 1
        FROM INSERTED I
        JOIN DELETED D
        ON I.EMPLOYEEID = D.EMPLOYEEID
        WHERE I.SALARY < D.SALARY
    )
    BEGIN
        RAISERROR('SALARY CANNOT BE REDUCED',16,1);
        ROLLBACK TRANSACTION;
    END
    ELSE
    BEGIN
        UPDATE E
        SET E.EMPLOYEENAME = I.EMPLOYEENAME,
            E.SALARY = I.SALARY,
            E.DEPARTMENT = I.DEPARTMENT
        FROM EMPLOYEES E
        JOIN INSERTED I
        ON E.EMPLOYEEID = I.EMPLOYEEID;
    END
END;
GO

