GO

CREATE TRIGGER TRG_REJECT_NEGATIVE_PRICE
ON PRODUCTS
INSTEAD OF INSERT
AS
BEGIN
    IF EXISTS (SELECT 1 FROM INSERTED WHERE PRICE < 0)
    BEGIN
        RAISERROR('NEGATIVE PRICE NOT ALLOWED',16,1);
        ROLLBACK TRANSACTION;
    END
    ELSE
    BEGIN
        INSERT INTO PRODUCTS
        (
            PRODUCTID,
            PRODUCTNAME,
            PRICE,
            CREATEDDATE
        )
        SELECT
            PRODUCTID,
            PRODUCTNAME,
            PRICE,
            CREATEDDATE
        FROM INSERTED;
    END
END;
GO

CREATE TRIGGER TRG_PRICE_REDUCTION_CHECK
ON PRODUCTS
INSTEAD OF UPDATE
AS
BEGIN
    IF EXISTS
    (
        SELECT 1
        FROM INSERTED I
        JOIN DELETED D
        ON I.PRODUCTID = D.PRODUCTID
        WHERE I.PRICE < D.PRICE * 0.8
    )
    BEGIN
        RAISERROR('PRICE CANNOT BE REDUCED BY MORE THAN 20 PERCENT',16,1);
        ROLLBACK TRANSACTION;
    END
    ELSE
    BEGIN
        UPDATE P
        SET P.PRODUCTNAME = I.PRODUCTNAME,
            P.PRICE = I.PRICE
        FROM PRODUCTS P
        JOIN INSERTED I
        ON P.PRODUCTID = I.PRODUCTID;
    END
END;
GO

