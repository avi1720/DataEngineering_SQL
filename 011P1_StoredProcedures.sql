DELIMITER //

CREATE PROCEDURE PLACE_NEW_ORDER(
    IN P_CUSTOMER_ID INT,
    IN P_TOTAL DECIMAL(10,2)
)
BEGIN
    INSERT INTO ORDERS(CUSTOMER_ID, ORDER_DATE, TOTAL_AMOUNT)
    VALUES(P_CUSTOMER_ID, CURDATE(), P_TOTAL);
END //

CREATE PROCEDURE ADD_PRODUCT_TO_ORDER(
    IN P_ORDER_ID INT,
    IN P_PRODUCT_ID INT,
    IN P_QTY INT,
    IN P_PRICE DECIMAL(10,2)
)
BEGIN
    INSERT INTO ORDER_DETAILS(ORDER_ID, PRODUCT_ID, QUANTITY, PRICE)
    VALUES(P_ORDER_ID, P_PRODUCT_ID, P_QTY, P_PRICE);

    UPDATE ORDERS
    SET TOTAL_AMOUNT = TOTAL_AMOUNT + (P_QTY * P_PRICE)
    WHERE ORDER_ID = P_ORDER_ID;
END //

CREATE PROCEDURE CHECK_STOCK(
    IN P_PRODUCT_ID INT
)
BEGIN
    SELECT STOCK
    FROM PRODUCTS
    WHERE PRODUCT_ID = P_PRODUCT_ID;
END //

CREATE PROCEDURE REDUCE_STOCK(
    IN P_PRODUCT_ID INT,
    IN P_QTY INT
)
BEGIN
    UPDATE PRODUCTS
    SET STOCK = STOCK - P_QTY
    WHERE PRODUCT_ID = P_PRODUCT_ID;
END //

CREATE PROCEDURE CANCEL_ORDER(
    IN P_ORDER_ID INT,
    IN P_PRODUCT_ID INT,
    IN P_QTY INT
)
BEGIN
    UPDATE PRODUCTS
    SET STOCK = STOCK + P_QTY
    WHERE PRODUCT_ID = P_PRODUCT_ID;

    DELETE FROM ORDERS
    WHERE ORDER_ID = P_ORDER_ID;
END //

CREATE PROCEDURE TOTAL_SPENT(
    IN P_CUSTOMER_ID INT,
    IN P_START_DATE DATE,
    IN P_END_DATE DATE
)
BEGIN
    SELECT SUM(TOTAL_AMOUNT) AS TOTAL_SPENT
    FROM ORDERS
    WHERE CUSTOMER_ID = P_CUSTOMER_ID
    AND ORDER_DATE BETWEEN P_START_DATE AND P_END_DATE;
END //

CREATE PROCEDURE PENDING_ORDERS(
    IN P_CUSTOMER_ID INT
)
BEGIN
    SELECT *
    FROM ORDERS
    WHERE CUSTOMER_ID = P_CUSTOMER_ID
    AND STATUS = 'PENDING';
END //

DELIMITER ;


