CREATE PROCEDURE GET_EMPLOYEES_BY_DEPARTMENT(
    IN P_DEPT_ID INT
)
BEGIN
    SELECT *
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = P_DEPT_ID;
END //

CREATE PROCEDURE INCREASE_EMPLOYEE_SALARY(
    IN P_EMP_ID INT,
    IN P_PERCENT DECIMAL(5,2)
)
BEGIN
    UPDATE EMPLOYEES
    SET SALARY = SALARY + (SALARY * P_PERCENT / 100)
    WHERE EMPLOYEE_ID = P_EMP_ID;
END //

CREATE PROCEDURE CALCULATE_ANNUAL_SALARY(
    IN P_EMP_ID INT
)
BEGIN
    SELECT EMPLOYEE_NAME,
           SALARY * 12 AS ANNUAL_SALARY
    FROM EMPLOYEES
    WHERE EMPLOYEE_ID = P_EMP_ID;
END //

CREATE PROCEDURE EMPLOYEES_GREATER_THAN_AMOUNT(
    IN P_AMOUNT DECIMAL(10,2)
)
BEGIN
    SELECT *
    FROM EMPLOYEES
    WHERE SALARY > P_AMOUNT;
END //

CREATE PROCEDURE DEPARTMENT_SALARY_REPORT()
BEGIN
    SELECT DEPARTMENT_ID,
           EMPLOYEE_NAME,
           SALARY
    FROM EMPLOYEES
    ORDER BY DEPARTMENT_ID;
