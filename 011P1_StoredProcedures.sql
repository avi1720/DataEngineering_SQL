CREATE PROCEDURE TRANSFER_MONEY_TXN(
    IN P_FROM_ACC INT,
    IN P_TO_ACC INT,
    IN P_AMOUNT DECIMAL(10,2)
)
BEGIN
    START TRANSACTION;

    UPDATE ACCOUNTS
    SET BALANCE = BALANCE - P_AMOUNT
    WHERE ACCOUNT_ID = P_FROM_ACC;

    UPDATE ACCOUNTS
    SET BALANCE = BALANCE + P_AMOUNT
    WHERE ACCOUNT_ID = P_TO_ACC;

    COMMIT;
END //

CREATE PROCEDURE PLACE_ORDER_MULTI_TABLE(
    IN P_CUSTOMER_ID INT,
    IN P_PRODUCT_ID INT,
    IN P_QTY INT
)
BEGIN
    DECLARE V_PRICE DECIMAL(10,2);

    SELECT PRICE
    INTO V_PRICE
    FROM PRODUCTS
    WHERE PRODUCT_ID = P_PRODUCT_ID;

    INSERT INTO ORDERS(CUSTOMER_ID, ORDER_DATE)
    VALUES(P_CUSTOMER_ID, CURDATE());

    INSERT INTO ORDER_ITEMS(ORDER_ID, PRODUCT_ID, QUANTITY, PRICE)
    VALUES(LAST_INSERT_ID(), P_PRODUCT_ID, P_QTY, V_PRICE);

    UPDATE PRODUCTS
    SET STOCK = STOCK - P_QTY
    WHERE PRODUCT_ID = P_PRODUCT_ID;
END //

CREATE PROCEDURE CUSTOMER_ORDER_SUMMARY(
    IN P_CUSTOMER_ID INT,
    IN P_START_DATE DATE,
    IN P_END_DATE DATE
)
BEGIN
    SELECT COUNT(*) AS TOTAL_ORDERS,
           SUM(TOTAL_AMOUNT) AS TOTAL_SPENDING
    FROM ORDERS
    WHERE CUSTOMER_ID = P_CUSTOMER_ID
    AND ORDER_DATE BETWEEN P_START_DATE AND P_END_DATE;
END //

CREATE PROCEDURE UPDATE_SALARY_AUDIT(
    IN P_EMP_ID INT,
    IN P_NEW_SALARY DECIMAL(10,2)
)
BEGIN
    DECLARE V_OLD_SALARY DECIMAL(10,2);

    SELECT SALARY
    INTO V_OLD_SALARY
    FROM EMPLOYEES
    WHERE EMPLOYEE_ID = P_EMP_ID;

    UPDATE EMPLOYEES
    SET SALARY = P_NEW_SALARY
    WHERE EMPLOYEE_ID = P_EMP_ID;

    INSERT INTO SALARY_AUDIT
    (EMPLOYEE_ID, OLD_SALARY, NEW_SALARY)
    VALUES
    (P_EMP_ID, V_OLD_SALARY, P_NEW_SALARY);
END //

CREATE PROCEDURE DELETE_CUSTOMER_IF_NO_ACTIVE_ORDERS(
    IN P_CUSTOMER_ID INT
)
BEGIN
    IF NOT EXISTS (
        SELECT *
        FROM ORDERS
        WHERE CUSTOMER_ID = P_CUSTOMER_ID
        AND STATUS = 'ACTIVE'
    ) THEN
        DELETE FROM CUSTOMERS
        WHERE CUSTOMER_ID = P_CUSTOMER_ID;
    ELSE
        SELECT 'ACTIVE ORDERS EXIST' AS MESSAGE;
    END IF;
END //

CREATE PROCEDURE CALCULATE_EMPLOYEE_BONUS(
    IN P_EMP_ID INT,
    IN P_RATING INT
)
BEGIN
    SELECT EMPLOYEE_NAME,
           SALARY,
           CASE
               WHEN P_RATING >= 5 THEN SALARY * 0.20
               WHEN P_RATING >= 3 THEN SALARY * 0.10
               ELSE SALARY * 0.05
           END AS BONUS
    FROM EMPLOYEES
    WHERE EMPLOYEE_ID = P_EMP_ID;
END //

CREATE PROCEDURE INACTIVE_CUSTOMERS()
BEGIN
    SELECT *
    FROM CUSTOMERS
    WHERE CUSTOMER_ID NOT IN (
        SELECT CUSTOMER_ID
        FROM ORDERS
        WHERE ORDER_DATE >= DATE_SUB(CURDATE(), INTERVAL 6 MONTH)
    );
END //

CREATE PROCEDURE MONTHLY_SALES_REPORT()
BEGIN
    SELECT COUNT(*) AS TOTAL_ORDERS,
           SUM(QUANTITY) AS TOTAL_QUANTITY_SOLD,
           SUM(TOTAL_AMOUNT) AS TOTAL_REVENUE
    FROM ORDERS;
END //

CREATE PROCEDURE CHECK_PRODUCT_ORDERABLE(
    IN P_PRODUCT_ID INT,
    IN P_QTY INT
)
BEGIN
    DECLARE V_STOCK INT;

    SELECT STOCK
    INTO V_STOCK
    FROM PRODUCTS
    WHERE PRODUCT_ID = P_PRODUCT_ID;

    IF V_STOCK >= P_QTY THEN
        SELECT 'ORDER CAN BE PLACED' AS STATUS;
    ELSE
        SELECT 'INSUFFICIENT STOCK' AS STATUS;
    END IF;
END //

CREATE PROCEDURE PROCESS_ORDER(
    IN P_CUSTOMER_ID INT,
    IN P_PRODUCT_ID INT,
    IN P_QTY INT
)
BEGIN
    DECLARE V_STOCK INT;
    DECLARE V_PRICE DECIMAL(10,2);

    START TRANSACTION;

    SELECT STOCK, PRICE
    INTO V_STOCK, V_PRICE
    FROM PRODUCTS
    WHERE PRODUCT_ID = P_PRODUCT_ID;

    IF V_STOCK >= P_QTY THEN

        INSERT INTO ORDERS(CUSTOMER_ID, ORDER_DATE, TOTAL_AMOUNT)
        VALUES(P_CUSTOMER_ID, CURDATE(), P_QTY * V_PRICE);

        UPDATE PRODUCTS
        SET STOCK = STOCK - P_QTY
        WHERE PRODUCT_ID = P_PRODUCT_ID;

        COMMIT;

    ELSE

        ROLLBACK;
        SELECT 'ORDER FAILED - INSUFFICIENT STOCK' AS MESSAGE;

    END IF;
END //
DELIMITER ;

