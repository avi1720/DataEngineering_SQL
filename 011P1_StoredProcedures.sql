CREATE PROCEDURE TOTAL_DEPARTMENT_SALARY_EXPENSE(
    IN P_DEPT_ID INT
)
BEGIN
    SELECT SUM(SALARY) AS TOTAL_SALARY_EXPENSE
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = P_DEPT_ID;
END //

