23. CREATE A PROCEDURE TO GENERATE A STUDENT RESULT REPORT CONTAINING STUDENT NAME, TOTAL, AVERAGE, GRADE, AND RESULT STATUS. */

DELIMITER //

CREATE PROCEDURE GET_STUDENTS_BY_COURSE(
    IN P_COURSE_ID INT
)
BEGIN
    SELECT *
    FROM STUDENTS
    WHERE COURSE_ID = P_COURSE_ID;
END //

CREATE PROCEDURE STUDENT_TOTAL_AVERAGE(
    IN P_STUDENT_ID INT
)
BEGIN
    SELECT STUDENT_NAME,
           (MARK1 + MARK2 + MARK3) AS TOTAL_MARKS,
           (MARK1 + MARK2 + MARK3) / 3 AS AVERAGE_MARKS
    FROM STUDENTS
    WHERE STUDENT_ID = P_STUDENT_ID;
END //

CREATE PROCEDURE CHECK_PASS_FAIL(
    IN P_STUDENT_ID INT
)
BEGIN
    DECLARE AVG_MARK DECIMAL(5,2);

    SELECT (MARK1 + MARK2 + MARK3) / 3
    INTO AVG_MARK
    FROM STUDENTS
    WHERE STUDENT_ID = P_STUDENT_ID;

    IF AVG_MARK >= 50 THEN
        SELECT 'PASS' AS RESULT;
    ELSE
        SELECT 'FAIL' AS RESULT;
    END IF;
END //

CREATE PROCEDURE STUDENTS_ABOVE_AVERAGE(
    IN P_AVG DECIMAL(5,2)
)
BEGIN
    SELECT *
    FROM STUDENTS
    WHERE (MARK1 + MARK2 + MARK3) / 3 > P_AVG;
END //

CREATE PROCEDURE STUDENT_RESULT_REPORT(
    IN P_STUDENT_ID INT
)
BEGIN
    SELECT STUDENT_NAME,
           (MARK1 + MARK2 + MARK3) AS TOTAL,
           (MARK1 + MARK2 + MARK3) / 3 AS AVERAGE,
           CASE
               WHEN (MARK1 + MARK2 + MARK3) / 3 >= 90 THEN 'A'
               WHEN (MARK1 + MARK2 + MARK3) / 3 >= 75 THEN 'B'
               WHEN (MARK1 + MARK2 + MARK3) / 3 >= 50 THEN 'C'
               ELSE 'D'
           END AS GRADE,
           CASE
               WHEN (MARK1 + MARK2 + MARK3) / 3 >= 50 THEN 'PASS'
               ELSE 'FAIL'
           END AS RESULT_STATUS
    FROM STUDENTS
    WHERE STUDENT_ID = P_STUDENT_ID;
END //

DELIMITER ;

