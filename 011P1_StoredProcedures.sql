/* STORED PROCEDURE

BANKING SYSTEM

1. CREATE A STORED PROCEDURE TO TRANSFER MONEY FROM ONE BANK ACCOUNT TO ANOTHER. THE PROCEDURE SHOULD DEDUCT THE AMOUNT FROM ONE ACCOUNT AND ADD IT TO THE OTHER ACCOUNT.
2. CREATE A PROCEDURE TO CHECK ACCOUNT BALANCE FOR A GIVEN ACCOUNT NUMBER.
3. CREATE A PROCEDURE TO DEPOSIT MONEY INTO A CUSTOMER'S ACCOUNT AND MAINTAIN A TRANSACTION HISTORY.
4. CREATE A PROCEDURE TO WITHDRAW MONEY ONLY IF THE ACCOUNT HAS SUFFICIENT BALANCE. OTHERWISE, DISPLAY AN APPROPRIATE MESSAGE.
5. CREATE A PROCEDURE TO GENERATE A MONTHLY BANK STATEMENT FOR A GIVEN CUSTOMER.*/

DELIMITER //

CREATE PROCEDURE TRANSFER_MONEY(
    IN P_FROM_ACC INT,
    IN P_TO_ACC INT,
    IN P_AMOUNT DECIMAL(10,2)
)
BEGIN
    UPDATE ACCOUNTS
    SET BALANCE = BALANCE - P_AMOUNT
    WHERE ACCOUNT_ID = P_FROM_ACC;

    UPDATE ACCOUNTS
    SET BALANCE = BALANCE + P_AMOUNT
    WHERE ACCOUNT_ID = P_TO_ACC;
END //

CREATE PROCEDURE CHECK_BALANCE(
    IN P_ACCOUNT_ID INT
)
BEGIN
    SELECT BALANCE
    FROM ACCOUNTS
    WHERE ACCOUNT_ID = P_ACCOUNT_ID;
END //

CREATE PROCEDURE DEPOSIT_MONEY(
    IN P_ACCOUNT_ID INT,
    IN P_AMOUNT DECIMAL(10,2)
)
BEGIN
    UPDATE ACCOUNTS
    SET BALANCE = BALANCE + P_AMOUNT
    WHERE ACCOUNT_ID = P_ACCOUNT_ID;

    INSERT INTO TRANSACTIONS(ACCOUNT_ID, AMOUNT, TRANSACTION_TYPE)
    VALUES(P_ACCOUNT_ID, P_AMOUNT, 'DEPOSIT');
END //

CREATE PROCEDURE WITHDRAW_MONEY(
    IN P_ACCOUNT_ID INT,
    IN P_AMOUNT DECIMAL(10,2)
)
BEGIN
    DECLARE CUR_BALANCE DECIMAL(10,2);

    SELECT BALANCE
    INTO CUR_BALANCE
    FROM ACCOUNTS
    WHERE ACCOUNT_ID = P_ACCOUNT_ID;

    IF CUR_BALANCE >= P_AMOUNT THEN
        UPDATE ACCOUNTS
        SET BALANCE = BALANCE - P_AMOUNT
        WHERE ACCOUNT_ID = P_ACCOUNT_ID;
    ELSE
        SELECT 'INSUFFICIENT BALANCE' AS MESSAGE;
    END IF;
END //

CREATE PROCEDURE MONTHLY_BANK_STATEMENT(
    IN P_ACCOUNT_ID INT
)
BEGIN
    SELECT *
    FROM TRANSACTIONS
    WHERE ACCOUNT_ID = P_ACCOUNT_ID
    AND MONTH(TRANSACTION_DATE) = MONTH(CURDATE())
    AND YEAR(TRANSACTION_DATE) = YEAR(CURDATE());
END //

DELIMITER ;

