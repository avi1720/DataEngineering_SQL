SELECT UPPER(PRODUCT_NAME) AS UPPER_NAME, LOWER(BRAND) AS BRAND_NAME FROM PRODUCTS;
SELECT LEFT(STUDENT_NAME,1) AS FIRST_CHAR, RIGHT(STUDENT_NAME,1) AS LAST_CHAR FROM STUDENTS;


