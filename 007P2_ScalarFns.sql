SELECT STUDENT_NAME, IF(ATTENDANCE >= 75, 'ELIGIBLE', 'NOT ELIGIBLE') AS ELIGIBILITY_STATUS FROM STUDENTS;
SELECT UPPER(EMPLOYEE_NAME) AS EMPLOYEE_NAME, ROUND(SALARY,2) AS SALARY FROM EMPLOYEES;
SELECT LOWER(PRODUCT_NAME) AS PRODUCT_NAME, PRICE*0.90 AS DISCOUNTED_PRICE FROM PRODUCTS;
SELECT UPPER(STUDENT_NAME) AS STUDENT_NAME, LEN(STUDENT_NAME) AS NAME_LENGTH FROM STUDENTS;
