SELECT EMPLOYEE_NAME, IFNULL(DEPARTMENT,'NOT ASSIGNED') AS DEPARTMENT FROM EMPLOYEES;
SELECT UPPER(PRODUCT_NAME) AS PRODUCT_NAME, ROUND(PRICE,2) AS PRICE, IFNULL(BRAND,'UNKNOWN') AS BRAND FROM PRODUCTS;
