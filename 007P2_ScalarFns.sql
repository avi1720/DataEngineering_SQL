/* E. CONDITIONAL SCALAR FUNCTIONS - 15 QUESTIONS

USING IF()

76. DISPLAY EMPLOYEE NAME AND SALARY. SHOW 'HIGH' IF SALARY >= 60000, OTHERWISE 'LOW'.
77. DISPLAY STUDENT NAME AND MARKS. SHOW 'PASS' IF MARKS >= 40, OTHERWISE 'FAIL'.
78. DISPLAY PRODUCT NAME AND STOCK. SHOW 'AVAILABLE' IF STOCK > 0, OTHERWISE 'OUT OF STOCK'.
79. DISPLAY EMPLOYEE NAME. SHOW 'EXPERIENCED' IF EXPERIENCE >= 5, OTHERWISE 'FRESHER'.
80. DISPLAY COURSE NAME. SHOW 'EXPENSIVE' IF FEES > 50000, OTHERWISE 'AFFORDABLE'.
81. DISPLAY BOOK NAME. SHOW 'PREMIUM' IF PRICE >= 1000, OTHERWISE 'REGULAR'.
82. DISPLAY CUSTOMER NAME. SHOW 'ADULT' IF AGE >= 18, OTHERWISE 'MINOR'.
83. DISPLAY PRODUCT NAME. SHOW 'LOW STOCK' IF STOCK < 10, OTHERWISE 'SUFFICIENT STOCK'.
84. DISPLAY EMPLOYEE NAME. SHOW 'ELIGIBLE' IF SALARY >= 50000, OTHERWISE 'NOT ELIGIBLE'.
85. DISPLAY STUDENT NAME. SHOW 'ELIGIBLE' IF ATTENDANCE >= 75, OTHERWISE 'NOT ELIGIBLE'. */

SELECT EMPLOYEE_NAME, IF(SALARY >= 60000, 'HIGH', 'LOW') AS SALARY_STATUS FROM EMPLOYEES;
SELECT STUDENT_NAME, IF(MARKS >= 40, 'PASS', 'FAIL') AS RESULT FROM STUDENTS;
SELECT PRODUCT_NAME, IF(STOCK > 0, 'AVAILABLE', 'OUT OF STOCK') AS STOCK_STATUS FROM PRODUCTS;
SELECT EMPLOYEE_NAME, IF(EXPERIENCE >= 5, 'EXPERIENCED', 'FRESHER') AS EXPERIENCE_STATUS FROM EMPLOYEES;
SELECT COURSE_NAME, IF(FEES > 50000, 'EXPENSIVE', 'AFFORDABLE') AS COURSE_STATUS FROM COURSES;
SELECT BOOK_NAME, IF(PRICE >= 1000, 'PREMIUM', 'REGULAR') AS BOOK_STATUS FROM BOOKS;
SELECT CUSTOMER_NAME, IF(AGE >= 18, 'ADULT', 'MINOR') AS CUSTOMER_STATUS FROM CUSTOMERS;
SELECT PRODUCT_NAME, IF(STOCK < 10, 'LOW STOCK', 'SUFFICIENT STOCK') AS STOCK_STATUS FROM PRODUCTS;
SELECT EMPLOYEE_NAME, IF(SALARY >= 50000, 'ELIGIBLE', 'NOT ELIGIBLE') AS ELIGIBILITY_STATUS FROM EMPLOYEES;
SELECT STUDENT_NAME, IF(ATTENDANCE >= 75, 'ELIGIBLE', 'NOT ELIGIBLE') AS ELIGIBILITY_STATUS FROM STUDENTS;

/* F. MIXED SCALAR FUNCTION QUESTIONS

