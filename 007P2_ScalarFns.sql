SELECT CUSTOMER_NAME, YEAR(REGISTRATION_DATE) AS REGISTRATION_YEAR FROM CUSTOMERS;
SELECT EMPLOYEE_NAME, MONTH(JOINING_DATE) AS JOINING_MONTH FROM EMPLOYEES;
