SELECT IFNULL(EMAIL, 'EMAIL MISSING') AS EMAIL FROM CUSTOMERS;
SELECT IFNULL(DEPARTMENT, 'NOT ASSIGNED') AS DEPARTMENT FROM EMPLOYEES;
SELECT IFNULL(DISCOUNT, 0) AS DISCOUNT FROM PRODUCTS;
SELECT IFNULL(FEES, 0) AS FEES FROM COURSES;
SELECT IFNULL(DISEASE, 'NOT SPECIFIED') AS DISEASE FROM PATIENTS;
