5. DISPLAY PRODUCTS WHOSE PRICE IS LESS THAN ANY PRODUCT PRICE IN THE ACCESSORIES CATEGORY.
6. DISPLAY BOOKS WHOSE PRICE IS GREATER THAN ANY BOOK PRICE IN THE TECHNOLOGY CATEGORY.
7. DISPLAY BOOKS WHOSE PRICE IS LESS THAN ANY BOOK PRICE IN THE SCIENCE CATEGORY.
