/* 
ANY AND ALL
OBJECTIVE
PRACTICE USING ANY AND ALL WITH SUBQUERIES.
• ANY → CONDITION SHOULD BE TRUE FOR AT LEAST ONE VALUE RETURNED BY THE SUBQUERY.
• ALL → CONDITION SHOULD BE TRUE FOR EVERY VALUE RETURNED BY THE SUBQUERY.
NOTE: ANY AND ALL ARE GENERALLY USED WITH A SUBQUERY AND COMPARISON OPERATORS SUCH AS >, <, =, >=, AND <=.


A. ANY – PRACTICE QUESTIONS

1. DISPLAY EMPLOYEES WHOSE SALARY IS GREATER THAN ANY SALARY OF EMPLOYEES IN THE HR DEPARTMENT.
2. DISPLAY EMPLOYEES WHOSE SALARY IS LESS THAN ANY SALARY OF EMPLOYEES IN THE IT DEPARTMENT.
3. DISPLAY EMPLOYEES WHOSE SALARY IS EQUAL TO ANY SALARY OF EMPLOYEES IN THE FINANCE DEPARTMENT.
