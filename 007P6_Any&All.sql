9. DISPLAY STUDENTS WHOSE AGE IS LESS THAN ANY AGE OF STUDENTS IN THE CSE DEPARTMENT.
10. DISPLAY COURSES WHOSE FEES ARE GREATER THAN ANY FEES OF COURSES OFFERED BY THE IT DEPARTMENT.
11. DISPLAY COURSES WHOSE FEES ARE LESS THAN ANY FEES OF COURSES OFFERED BY THE CSE DEPARTMENT.
