13. DISPLAY PRODUCTS WHOSE PRICE IS GREATER THAN ANY PRICE OF PRODUCTS BELONGING TO THE SAMSUNG BRAND.
14. DISPLAY BOOKS WHOSE QUANTITY IS GREATER THAN ANY QUANTITY OF BOOKS IN THE TECHNOLOGY CATEGORY.
