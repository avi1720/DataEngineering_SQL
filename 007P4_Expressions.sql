A. ARITHMETIC EXPRESSIONS – 20 QUESTIONS

USE OPERATORS: +, -, *, /, %

1. DISPLAY EACH EMPLOYEE'S SALARY AND CALCULATE A ₹5,000 BONUS.
2. DISPLAY EACH EMPLOYEE'S SALARY AFTER ADDING 10% INCREMENT.
3. DISPLAY EACH EMPLOYEE'S SALARY AFTER DEDUCTING ₹2,000.
