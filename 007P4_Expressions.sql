11. DISPLAY EACH COURSE'S FEES AND CALCULATE THE FEES AFTER ADDING 5% GST.
12. DISPLAY EACH COURSE'S FEES AND CALCULATE THE FEES AFTER A 10% DISCOUNT.
13. DISPLAY PRODUCT PRICE, QUANTITY, AND CALCULATE THE TOTAL PRODUCT VALUE.
14. DISPLAY BOOK PRICE, QUANTITY, AND CALCULATE THE TOTAL INVENTORY VALUE.
15. DISPLAY EMPLOYEE SALARY AND CALCULATE THE ANNUAL SALARY AFTER A 10% INCREMENT.
16. DISPLAY PRODUCT PRICE AND CALCULATE THE PRICE AFTER 20% DISCOUNT + 18% GST.
17. DISPLAY THE TOTAL SALARY OF EACH EMPLOYEE AFTER ADDING A ₹3,000 ALLOWANCE.
18. DISPLAY COURSE FEES AND CALCULATE THE FEES PAYABLE AFTER A 15% SCHOLARSHIP DISCOUNT.
19. DISPLAY PRODUCT PRICE AND STOCK QUANTITY AND CALCULATE THE TOTAL STOCK VALUE.
20. DISPLAY EMPLOYEE SALARY AND CALCULATE THE DIFFERENCE BETWEEN SALARY AND 50000. */

SELECT SALARY, SALARY + 5000 AS BONUS_SALARY FROM EMPLOYEES;
SELECT SALARY, SALARY * 1.10 AS INCREMENTED_SALARY FROM EMPLOYEES;
SELECT SALARY, SALARY - 2000 AS UPDATED_SALARY FROM EMPLOYEES;
SELECT SALARY, SALARY * 12 AS ANNUAL_SALARY FROM EMPLOYEES;
SELECT SALARY, SALARY * 0.95 AS MONTHLY_SALARY_AFTER_DEDUCTION FROM EMPLOYEES;
SELECT PRICE, PRICE * 1.18 AS PRICE_AFTER_GST FROM PRODUCTS;
SELECT PRICE, PRICE * 0.90 AS PRICE_AFTER_DISCOUNT FROM PRODUCTS;
SELECT PRICE, PRICE * 0.15 AS DISCOUNT_AMOUNT FROM PRODUCTS;
SELECT PRICE, PRICE * 1.10 AS PRICE_AFTER_TAX FROM BOOKS;
SELECT PRICE, PRICE * 0.80 AS PRICE_AFTER_DISCOUNT FROM BOOKS;
SELECT FEES, FEES * 1.05 AS FEES_AFTER_GST FROM COURSES;
SELECT FEES, FEES * 0.90 AS FEES_AFTER_DISCOUNT FROM COURSES;
SELECT PRICE, QUANTITY, PRICE * QUANTITY AS TOTAL_PRODUCT_VALUE FROM PRODUCTS;
SELECT PRICE, QUANTITY, PRICE * QUANTITY AS TOTAL_INVENTORY_VALUE FROM BOOKS;
SELECT SALARY, (SALARY * 12) * 1.10 AS ANNUAL_SALARY_AFTER_INCREMENT FROM EMPLOYEES;
SELECT PRICE, (PRICE * 0.80) * 1.18 AS FINAL_PRICE FROM PRODUCTS;
SELECT SALARY, SALARY + 3000 AS TOTAL_SALARY FROM EMPLOYEES;
SELECT FEES, FEES * 0.85 AS PAYABLE_FEES FROM COURSES;
SELECT PRICE, STOCK_QUANTITY, PRICE * STOCK_QUANTITY AS TOTAL_STOCK_VALUE FROM PRODUCTS;
SELECT SALARY, SALARY - 50000 AS DIFFERENCE FROM EMPLOYEES;

