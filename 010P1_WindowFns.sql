A. ROW_NUMBER()

1. DISPLAY ALL EMPLOYEES WITH A UNIQUE SEQUENTIAL ROW NUMBER BASED ON THEIR SALARY IN ASCENDING ORDER.
2. DISPLAY EMPLOYEES WITH A ROW NUMBER BASED ON SALARY IN DESCENDING ORDER.
3. ASSIGN A ROW NUMBER TO EMPLOYEES SEPARATELY WITHIN EACH DEPARTMENT.
4. DISPLAY THE TOP 3 EMPLOYEES FROM EACH DEPARTMENT USING ROW_NUMBER().
5. ASSIGN ROW NUMBERS TO STUDENTS BASED ON THEIR MARKS FROM HIGHEST TO LOWEST WITHIN EACH DEPARTMENT. */

SELECT *,
       ROW_NUMBER() OVER(ORDER BY SALARY ASC) AS ROW_NUM
FROM EMPLOYEES;

SELECT *,
       ROW_NUMBER() OVER(ORDER BY SALARY DESC) AS ROW_NUM
FROM EMPLOYEES;

SELECT *,
       ROW_NUMBER() OVER(PARTITION BY DEPARTMENT ORDER BY SALARY DESC) AS ROW_NUM
FROM EMPLOYEES;

SELECT *
FROM
(
    SELECT *,
           ROW_NUMBER() OVER(PARTITION BY DEPARTMENT ORDER BY SALARY DESC) AS ROW_NUM
    FROM EMPLOYEES
) T
WHERE ROW_NUM <= 3;

SELECT *,
       ROW_NUMBER() OVER(PARTITION BY DEPARTMENT ORDER BY MARKS DESC) AS ROW_NUM
FROM STUDENTS;

