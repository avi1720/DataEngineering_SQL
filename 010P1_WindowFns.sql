/* G. LEAD()

28. DISPLAY EACH EMPLOYEE'S SALARY ALONG WITH THE SALARY OF THE NEXT EMPLOYEE BASED ON EMPLOYEE ID.
29. DISPLAY EACH EMPLOYEE'S JOINING DATE ALONG WITH THE JOINING DATE OF THE NEXT EMPLOYEE.
