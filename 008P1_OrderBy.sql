63. DISPLAY THE AVERAGE SALARY OF EACH DEPARTMENT AND SORT BY AVERAGE SALARY IN DESCENDING ORDER.
64. DISPLAY THE MINIMUM SALARY OF EACH DEPARTMENT AND SORT BY MINIMUM SALARY ASCENDING.
65. DISPLAY THE MAXIMUM SALARY OF EACH DEPARTMENT AND SORT BY MAXIMUM SALARY DESCENDING.
66. DISPLAY THE TOTAL SALARY OF EACH DEPARTMENT AND SORT BY TOTAL SALARY DESCENDING.
67. DISPLAY THE AVERAGE PRODUCT PRICE FOR EACH CATEGORY AND SORT BY AVERAGE PRICE DESCENDING.
68. DISPLAY THE MAXIMUM PRODUCT PRICE FOR EACH CATEGORY AND SORT BY MAXIMUM PRICE DESCENDING.
69. DISPLAY THE MINIMUM PRODUCT PRICE FOR EACH CATEGORY AND SORT BY MINIMUM PRICE ASCENDING.
70. DISPLAY THE TOTAL STOCK FOR EACH PRODUCT CATEGORY AND SORT BY TOTAL STOCK DESCENDING. */

SELECT DEPARTMENT, COUNT(*) AS EMPLOYEE_COUNT FROM EMPLOYEES GROUP BY DEPARTMENT ORDER BY EMPLOYEE_COUNT DESC;
SELECT DEPARTMENT, COUNT(*) AS STUDENT_COUNT FROM STUDENTS GROUP BY DEPARTMENT ORDER BY STUDENT_COUNT ASC;
SELECT DEPARTMENT, AVG(SALARY) AS AVG_SALARY FROM EMPLOYEES GROUP BY DEPARTMENT ORDER BY AVG_SALARY DESC;
SELECT DEPARTMENT, MIN(SALARY) AS MIN_SALARY FROM EMPLOYEES GROUP BY DEPARTMENT ORDER BY MIN_SALARY ASC;
SELECT DEPARTMENT, MAX(SALARY) AS MAX_SALARY FROM EMPLOYEES GROUP BY DEPARTMENT ORDER BY MAX_SALARY DESC;
SELECT DEPARTMENT, SUM(SALARY) AS TOTAL_SALARY FROM EMPLOYEES GROUP BY DEPARTMENT ORDER BY TOTAL_SALARY DESC;
SELECT CATEGORY, AVG(PRICE) AS AVG_PRICE FROM PRODUCTS GROUP BY CATEGORY ORDER BY AVG_PRICE DESC;
SELECT CATEGORY, MAX(PRICE) AS MAX_PRICE FROM PRODUCTS GROUP BY CATEGORY ORDER BY MAX_PRICE DESC;
SELECT CATEGORY, MIN(PRICE) AS MIN_PRICE FROM PRODUCTS GROUP BY CATEGORY ORDER BY MIN_PRICE ASC;
SELECT CATEGORY, SUM(STOCK_QUANTITY) AS TOTAL_STOCK FROM PRODUCTS GROUP BY CATEGORY ORDER BY TOTAL_STOCK DESC;

