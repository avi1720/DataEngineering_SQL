/* E. ORDER BY WITH ALIAS

51. DISPLAY EMPLOYEE SALARY × 12 WITH THE ALIAS ANNUAL_SALARY AND SORT BY ANNUAL_SALARY DESCENDING.
52. DISPLAY PRODUCT PRICE × QUANTITY WITH THE ALIAS TOTAL_VALUE AND SORT BY TOTAL_VALUE DESCENDING.
53. DISPLAY STUDENT NAME LENGTH WITH THE ALIAS NAME_LENGTH AND SORT BY NAME_LENGTH ASCENDING.
54. DISPLAY EMPLOYEE SALARY AFTER A 10% INCREMENT WITH THE ALIAS INCREMENTED_SALARY AND SORT BY IT DESCENDING.
55. DISPLAY PRODUCT PRICE AFTER DISCOUNT WITH THE ALIAS DISCOUNTED_PRICE AND SORT BY IT ASCENDING.
56. DISPLAY COURSE FEES AFTER DISCOUNT WITH THE ALIAS FINAL_FEES AND SORT BY IT DESCENDING.
57. DISPLAY STUDENT AGE CATEGORY USING CASE WITH THE ALIAS AGE_CATEGORY AND SORT BY THE ALIAS.
58. DISPLAY EMPLOYEE SALARY CATEGORY USING CASE WITH THE ALIAS SALARY_CATEGORY AND SORT BY IT.
59. DISPLAY PRODUCT STOCK STATUS USING CASE WITH THE ALIAS STOCK_STATUS AND SORT BY IT.
60. DISPLAY MOVIE RATING CATEGORY USING CASE WITH THE ALIAS RATING_CATEGORY AND SORT BY IT. */

SELECT NAME, SALARY * 12 AS ANNUAL_SALARY FROM EMPLOYEES ORDER BY ANNUAL_SALARY DESC;
SELECT PRODUCT_NAME, PRICE * QUANTITY AS TOTAL_VALUE FROM PRODUCTS ORDER BY TOTAL_VALUE DESC;
SELECT NAME, LENGTH(NAME) AS NAME_LENGTH FROM STUDENTS ORDER BY NAME_LENGTH ASC;
SELECT NAME, SALARY * 1.10 AS INCREMENTED_SALARY FROM EMPLOYEES ORDER BY INCREMENTED_SALARY DESC;
SELECT PRODUCT_NAME, PRICE * 0.90 AS DISCOUNTED_PRICE FROM PRODUCTS ORDER BY DISCOUNTED_PRICE ASC;
SELECT COURSE_NAME, FEES * 0.85 AS FINAL_FEES FROM COURSES ORDER BY FINAL_FEES DESC;
SELECT NAME, CASE WHEN AGE < 18 THEN 'MINOR' ELSE 'ADULT' END AS AGE_CATEGORY FROM STUDENTS ORDER BY AGE_CATEGORY;
SELECT NAME, CASE WHEN SALARY >= 50000 THEN 'HIGH' ELSE 'LOW' END AS SALARY_CATEGORY FROM EMPLOYEES ORDER BY SALARY_CATEGORY;
SELECT PRODUCT_NAME, CASE WHEN STOCK_QUANTITY > 0 THEN 'IN STOCK' ELSE 'OUT OF STOCK' END AS STOCK_STATUS FROM PRODUCTS ORDER BY STOCK_STATUS;
SELECT MOVIE_NAME, CASE WHEN RATING >= 4 THEN 'GOOD' ELSE 'AVERAGE' END AS RATING_CATEGORY FROM MOVIES ORDER BY RATING_CATEGORY;

/* F. ORDER BY WITH AGGREGATE FUNCTIONS

